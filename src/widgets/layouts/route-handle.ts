/**
 * 라우트가 자기 화면 규격을 레이아웃에 알리는 통로 (`<Route handle={...}>`).
 *
 * 채팅처럼 화면 높이에 딱 맞아야 하는 페이지는 `MainLayout` 의 기본 규격
 * (`min-h-screen` + 넉넉한 상하 여백)과 맞지 않는다. 그렇다고 페이지가 여백을
 * 되돌리는 것은 규칙 위반이고(여백의 주인은 레이아웃이다), 별도 레이아웃 라우트를
 * 만들면 사이드바가 새 트리로 리마운트돼 펼쳐 둔 메뉴가 접히고 전환이 깜빡인다.
 *
 * 그래서 **레이아웃 인스턴스는 하나로 두고 라우트가 규격만 선언한다.**
 */
export type MainRouteHandle = {
  /**
   * 뷰포트 높이에 맞추고 스크롤을 페이지 안쪽에 가둔다.
   *
   * 켜면 `main` 이 `h-dvh` 플렉스 열이 되고 본문이 남은 높이를 가져간다.
   * 페이지는 `h-full min-h-0` 로 그 높이를 받아 쓴다.
   */
  fill?: boolean;
};

/** 채팅 화면 — 대화 목록과 말풍선이 각자 스크롤한다 */
export const CHAT_ROUTE_HANDLE: MainRouteHandle = { fill: true };
